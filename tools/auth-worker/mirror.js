// Copies the app's own trip-edit logic out of index.html into worker.js, between the
// MIRROR markers. The Worker deploys as ONE pasted file (no bundler), so it cannot
// import from index.html; this keeps its copy byte-identical instead.
//
//   node tools/auth-worker/mirror.js          rewrite the block
//   node tools/auth-worker/mirror.js --check  exit 1 if the block is out of date
//
// tools/tests/workertripedits_test.js runs the same comparison, so a change to any of
// these functions in index.html fails the suite until this is re-run.
const fs = require('fs');
const path = require('path');

const MIRROR_NAMES = [
  'TRIPSY_CUSTOM_CATEGORY_SPA_SLUG', 'TRIPSY_CUSTOM_CATEGORY_RECEPTION_SLUG', 'TRIPSY_CUSTOM_CATEGORY_COOKING_SLUG',
  'TRIPSY_CUSTOM_CATEGORY_LABELS', 'TRIPSY_ACTIVITY_TYPES', 'TRIPSY_TRANSPORTATION_TYPES',
  'TRIPSY_ACTIVITY_CATEGORY_TO_TYPE', 'TRIPSY_AIRPORT_ZONE_GROUPS',
  'parseTripLocalParts', 'tripsyZonedWallClockToUtcMs', 'tripsyAirportCodeOf',
  'tripsySlugToLabel', 'tripsyActivityCategoryToType', 'tripsyShortenPlaceDescription',
  'tripsyTransportationFallbackSummary', 'tripsySeatLabel', 'tripsyFlightDurationLabel',
  'tripsySeatAndFlightTimeLabel', 'tripsyRawToDisplay', 'tripsyEventKey', 'tripsyMintLocalId',
  'tripsyBlankRaw', 'applyTripsyChangeToTrips', 'TRIPSY_TRIP_EDIT_KNOWN_TYPES', 'tripsyTripEditCreateIdentity',
];
const BEGIN = '// >>> MIRROR BEGIN (generated by tools/auth-worker/mirror.js -- do not edit by hand)';
const END = '// <<< MIRROR END';

// One top-level `function X` / `const X` declaration, exactly as written.
function grab(lines, name) {
  const i = lines.findIndex(l => new RegExp(`^(async )?function ${name}\\b`).test(l) || new RegExp(`^const ${name}\\b`).test(l));
  if (i < 0) return null;
  if (/^const /.test(lines[i]) && /;\s*$/.test(lines[i])) return lines[i];
  const out = [lines[i]];
  for (let j = i + 1; j < lines.length; j++) { out.push(lines[j]); if (/^(}|\]|\});?\s*$/.test(lines[j])) return out.join('\n'); }
  return null;
}
// The field KEYS a blank event starts with (tripsyBlankRaw reads only .key).
function editFieldKeys(lines) {
  const agent = (grab(lines, 'TRIPSY_TRAVEL_AGENT_FIELDS').match(/key: '(\w+)'/g) || []).map(k => k.slice(6, -1));
  const body = grab(lines, 'TRIPSY_EDIT_FIELDS');
  const out = {};
  for (const resource of ['activity', 'hosting', 'transportation']) {
    const m = body.match(new RegExp(`\\n  ${resource}: \\[([\\s\\S]*?)\\n  \\],`));
    const keys = [];
    for (const line of m[1].split('\n')) {
      if (/\.\.\.TRIPSY_TRAVEL_AGENT_FIELDS/.test(line)) keys.push(...agent);
      const k = line.match(/key: '(\w+)'/);
      if (k) keys.push(k[1]);
    }
    out[resource] = keys;
  }
  return out;
}
function buildBlock(html) {
  const lines = html.split('\n');
  const parts = [BEGIN, 'let tripsyDecryptedTrips = null;'];
  const keys = editFieldKeys(lines);
  parts.push('const TRIPSY_EDIT_FIELDS = {\n' + Object.entries(keys).map(([r, ks]) =>
    `  ${r}: [${ks.map(k => `{ key: '${k}' }`).join(', ')}],`).join('\n') + '\n};');
  for (const name of MIRROR_NAMES) {
    const g = grab(lines, name);
    if (!g) throw new Error(`mirror: ${name} not found in index.html`);
    parts.push(g);
    if (name === 'TRIPSY_AIRPORT_ZONE_GROUPS') {
      parts.push('const TRIPSY_AIRPORT_ZONES = {};\nfor (const [zone, codes] of Object.entries(TRIPSY_AIRPORT_ZONE_GROUPS)) for (const c of codes.split(\' \')) TRIPSY_AIRPORT_ZONES[c] = zone;');
    }
  }
  parts.push(END);
  return parts.join('\n');
}
function currentBlock(worker) {
  const a = worker.indexOf(BEGIN), b = worker.indexOf(END);
  return a < 0 || b < 0 ? null : worker.slice(a, b + END.length);
}
module.exports = { MIRROR_NAMES, BEGIN, END, grab, editFieldKeys, buildBlock, currentBlock };

if (require.main === module) {
  const root = path.join(__dirname, '..', '..');
  const workerPath = path.join(__dirname, 'worker.js');
  const worker = fs.readFileSync(workerPath, 'utf8');
  const block = buildBlock(fs.readFileSync(path.join(root, 'index.html'), 'utf8'));
  const cur = currentBlock(worker);
  if (cur === null) { console.error('mirror: markers not found in worker.js'); process.exit(1); }
  if (process.argv.includes('--check')) {
    if (cur !== block) { console.error('mirror: worker.js is OUT OF DATE -- run node tools/auth-worker/mirror.js'); process.exit(1); }
    console.log('mirror: worker.js matches index.html');
  } else {
    fs.writeFileSync(workerPath, worker.replace(cur, () => block));
    console.log(cur === block ? 'mirror: already up to date' : 'mirror: worker.js updated');
  }
}
